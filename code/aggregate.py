#!/usr/bin/env python3
"""Aggregate all ch8 runs into results/RESULTS.md (the source of every number in main.tex).

Reads results/extract*/summary.json, results/mine_*/rules.json and
results/mine_*/results/hunt_eval.json for each split salt, results/portability.json
and results/sql_check.json if present.

usage: aggregate.py RESULTS_DIR
"""
import glob
import json
import os
import statistics as st
import sys


def ms(xs):
    xs = list(xs)
    if not xs:
        return "n/a"
    if len(xs) == 1:
        return "%.3f" % xs[0]
    return "%.3f +- %.3f (n=%d, min %.3f, max %.3f)" % (st.mean(xs), st.stdev(xs), len(xs), min(xs), max(xs))


def fm(m):
    return ("P %.3f [%.3f, %.3f] (%d/%d)  R %.3f [%.3f, %.3f] (%d/%d)  F1 %.3f" %
            (m["precision"], *m["precision_ci"], m["tp"], m["tp"] + m["fp"],
             m["recall"], *m["recall_ci"], m["tp"], m["tp"] + m["fn"], m["f1"]))


def main():
    R = sys.argv[1]
    L = ["# ch8 results", "", "Generated by code/aggregate.py. Do not edit by hand.", ""]
    for ex in sorted(glob.glob(os.path.join(R, "extract*", "summary.json"))):
        s = json.load(open(ex))
        L += ["## %s" % os.path.relpath(ex, R),
              "packets %d (v4 %d, v6 %d); sources %d; duration %.3f s" %
              (s["packets"], s.get("v4", 0), s.get("v6", 0), s["sources"], s["duration_s"]),
              "packets matched: anomalous %d, suspicious %d, notice %d; rules used %d; dropped ip-less %s" %
              (s.get("anomalous", 0), s.get("suspicious", 0), s.get("notice", 0), s["rules"],
               s.get("rules_dropped_ipless")),
              "hosts: anomalous %d, benign %d; params %s" % (s["hosts_anomalous"], s["hosts_benign"], s["params"]), ""]
    runs = sorted(glob.glob(os.path.join(R, "mine_*", "results", "hunt_eval.json")))
    agg = {"rules": [], "expert": [], "tree": [], "perm": [], "nrules": [], "nperm": []}
    for path in runs:
        run = os.path.basename(os.path.dirname(os.path.dirname(path)))
        e = json.load(open(path))
        meta = json.load(open(os.path.join(R, run, "rules.json")))
        L += ["## %s" % run,
              "test hosts %d (%d anomalous); train hosts used %s" %
              (e["n_test"], e["n_test_anomalous"], meta["train_counts"]),
              "test hosts by taxonomy: %s" % e.get("test_by_taxonomy"), "",
              "### Ordered rules (ANOM consequent)", "",
              "| # | rule | len | host P | host R | bin conf | conf permuted | conf collapsed | window gain |",
              "|---|---|---|---|---|---|---|---|---|"]
        for i, r in enumerate(e["rules"]["ordered"], 1):
            L.append("| %d | `%s |=> ##[%g:%g] ANOM` | %d | %.3f (%d/%d) | %.3f (%d/%d) | %.3f (%d) | %.3f | %.3f | %+.3f |" % (
                i, r["antecedent"], r["lo"], r["hi"], r["length"], r["host"]["precision"], r["host"]["tp"],
                r["host"]["tp"] + r["host"]["fp"], r["host"]["recall"], r["host"]["tp"],
                r["host"]["tp"] + r["host"]["fn"], r["bin_confidence"], r["bin_completions"],
                r["bin_confidence_permuted"], r["bin_confidence_collapsed"], r["window_gain"]))
        L += ["", "playbook (ordered): " + fm(e["playbook_ordered"]),
              "playbook recall by taxonomy: %s" % e.get("playbook_recall_by_taxonomy"),
              "rules mined from permuted traces: %d; their playbook: %s" %
              (len(e["rules"]["permuted"]), fm(e["playbook_permuted"])), "",
              "### Permuted-trace rules", ""]
        for r in e["rules"]["permuted"]:
            L.append("- `%s |=> ##[%g:%g] ANOM`: %s" % (r["antecedent"], r["lo"], r["hi"], fm(r["host"])))
        L += ["", "### Expert hypotheses", ""]
        for x in e.get("expert", []):
            L.append("- %s `%s`: %s; bin conf %.3f (%d)" % (x["name"], x["antecedent"], fm(x["host"]),
                                                          x["bin_confidence"], x["bin_completions"]))
        L += ["", "expert playbook: " + fm(e["playbook_expert"]),
              "expert recall by taxonomy: %s" % e.get("playbook_expert_recall_by_taxonomy"), ""]
        tb = e["tree_baseline"]
        if "precision" in tb:
            L += ["tree (depth %s): %s; leaves %d" % (tb.get("depth"), fm(tb), tb["leaves"]),
                  "```", tb["tree"].rstrip(), "```", ""]
            agg["tree"].append(tb)
        agg["rules"].append(e["playbook_ordered"])
        agg["perm"].append(e["playbook_permuted"])
        agg["expert"].append(e["playbook_expert"])
        agg["nrules"].append(len(e["rules"]["ordered"]))
        agg["nperm"].append(len(e["rules"]["permuted"]))
        gains = [r["window_gain"] for r in e["rules"]["ordered"]]
        multi = [r for r in e["rules"]["ordered"] if r["steps"] > 1 or r["hi"] >= 1]
        L += ["window gains: %s; rules with a sequence or window >= 1 s: %d of %d" %
              (gains, len(multi), len(e["rules"]["ordered"])), ""]
    if runs:
        L += ["## Across splits", "",
              "ordered rules per split: %s" % agg["nrules"],
              "permuted-trace rules per split: %s" % agg["nperm"],
              "rule playbook precision: " + ms(m["precision"] for m in agg["rules"]),
              "rule playbook recall:    " + ms(m["recall"] for m in agg["rules"]),
              "rule playbook F1:        " + ms(m["f1"] for m in agg["rules"]),
              "permuted playbook precision: " + ms(m["precision"] for m in agg["perm"]),
              "permuted playbook recall:    " + ms(m["recall"] for m in agg["perm"]),
              "expert playbook precision: " + ms(m["precision"] for m in agg["expert"]),
              "expert playbook recall:    " + ms(m["recall"] for m in agg["expert"]),
              "tree precision: " + ms(m["precision"] for m in agg["tree"]),
              "tree recall:    " + ms(m["recall"] for m in agg["tree"]),
              "tree F1:        " + ms(m["f1"] for m in agg["tree"]),
              "tree leaves:    %s" % [m["leaves"] for m in agg["tree"]], ""]
    p = os.path.join(R, "portability.json")
    if os.path.exists(p):
        q = json.load(open(p))
        L += ["## Portability (rules of the main split scored on the other day)",
              "test hosts %d (%d anomalous); by taxonomy %s" % (q["n_test"], q["n_test_anomalous"], q["test_by_taxonomy"]),
              "rule playbook: " + fm(q["playbook"]),
              "rule playbook recall by taxonomy: %s" % q["playbook_recall_by_taxonomy"],
              "expert playbook: " + fm(q["playbook_expert"])]
        if "precision" in q["tree_baseline"]:
            L.append("tree: " + fm(q["tree_baseline"]))
            L.append("tree recall by taxonomy: %s" % q.get("tree_recall_by_taxonomy"))
        for r in q["rules"]:
            L.append("- `%s ##[%g:%g]`: %s" % (r["antecedent"], r["lo"], r["hi"], fm(r["host"])))
        L.append("")
    p = os.path.join(R, "sql_check.json")
    if os.path.exists(p):
        q = json.load(open(p))
        L += ["## SQL compilation check", "%d of %d rules return identical host sets" % (q["equal"], q["rules"]), ""]
        if q["detail"]:
            L += ["Example (rule 1):", "```sql", q["detail"][0]["sql"], "```", ""]
    open(os.path.join(R, "RESULTS.md"), "w").write("\n".join(L))
    print("\n".join(L[:12]))


if __name__ == "__main__":
    main()
