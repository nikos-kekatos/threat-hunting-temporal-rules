#!/usr/bin/env python3
"""Delay-sweep figure as pgfplots, generated from results_xai_v2/SUMMARY.md (2026-10-24).

Replaces the matplotlib fig_delay.pdf (code/fig_delay.py) with the same series and data:
host F1 (mean over three seeds) and explanation size (seed 1) against the upper bound G of the
delay range [1, G]. Series: PSI-Miner (bias +1, rule selected on training hosts), RIPPER with
L = 8 and L = 3, Anchors with L = 3. Writes fig_delay.tex, which main.tex \\input's.
usage: make_tikz_fig_delay.py [SUMMARY.md] [OUT.tex]
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SUMMARY = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "results_xai_v2", "SUMMARY.md")
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "..", "fig_delay.tex")

# (legend label, lag budget, method, view, pgf style)
SERIES = [
    ("PSI-Miner", "L3", "psiminer_trainsel_b1", "temporal",
     "color=c1, mark=*, solid"),
    ("RIPPER, $L{=}8$", "L8", "ripper", "bin",
     "color=c2, mark=square*, dashed"),
    ("RIPPER, $L{=}3$", "L3", "ripper", "bin",
     "color=c3, mark=triangle*, dotted"),
    ("Anchors, $L{=}3$", "L3", "anchors", "bin",
     "color=c4, mark=diamond*, dashdotted"),
]
GS = [2, 4, 6, 8]


def load():
    rows = {}
    for line in open(SUMMARY):
        c = [x.strip() for x in line.strip().strip("|").split("|")]
        if len(c) == 8 and c[0].startswith("gap1-"):
            rows[(int(c[0][5:]), c[1], c[2], c[3])] = (c[4].split()[0], c[7])
    return rows


def size_of(s):
    m = re.search(r"(\d+) conds", s) or re.search(r"(\d+) literals", s)
    return int(m.group(1))


def main():
    rows = load()
    data = {}
    for label, L, meth, view, _ in SERIES:
        data[label] = [(g, rows[(g, L, meth, view)][0], size_of(rows[(g, L, meth, view)][1])) for g in GS]
    # headline values quoted in the text
    assert data["PSI-Miner"][-1][1] == "0.993", data["PSI-Miner"]
    assert max(d[2] for d in data["PSI-Miner"]) == 4
    assert data["RIPPER, $L{=}8$"][-1][2] == 23
    assert [d[1] for d in data["Anchors, $L{=}3$"]][1:] == ["0.770", "0.546", "0.636"]

    out = []
    out.append("% generated by code/make_tikz_fig_delay.py from results_xai_v2/SUMMARY.md; do not edit by hand")
    out.append("\\begin{tikzpicture}")
    out.append("\\definecolor{c1}{HTML}{2A78D6}\\definecolor{c2}{HTML}{EB6834}"
               "\\definecolor{c3}{HTML}{1BAF7A}\\definecolor{c4}{HTML}{B07800}")
    out.append("\\begin{groupplot}[group style={group size=1 by 2, vertical sep=6pt, "
               "x descriptions at=edge bottom},")
    out.append("  scale only axis, width=0.83\\columnwidth, xmin=1.6, xmax=8.4, xtick={2,4,6,8},")
    out.append("  tick label style={font=\\scriptsize}, label style={font=\\footnotesize},")
    out.append("  every axis plot/.append style={line width=1pt, mark size=1.8pt},")
    out.append("  ymajorgrids, grid style={black!12}, axis line style={black!60},")
    out.append("  xlabel={Upper bound $G$ of the delay range $[1,G]$ (s)}]")
    # top panel: F1
    out.append("\\nextgroupplot[height=2.9cm, ymin=0.45, ymax=1.04, ylabel={Host F1},")
    out.append("  legend style={font=\\scriptsize, draw=none, at={(0.5,1.03)}, anchor=south,")
    out.append("    legend columns=2, /tikz/every even column/.append style={column sep=5pt}}]")
    for label, _, _, _, style in SERIES:
        coords = " ".join(f"({g},{f1})" for g, f1, _ in data[label])
        out.append(f"\\addplot[{style}] coordinates {{{coords}}};")
        out.append(f"\\addlegendentry{{{label}}}")
    out.append("\\addplot[black!55, line width=0.6pt, densely dashed, mark=none, forget plot] "
               "coordinates {(1.6,0.645) (8.4,0.645)};")
    out.append("\\node[font=\\scriptsize, text=black!65, anchor=north west] at (axis cs:1.65,0.59) "
               "{flags every host (0.645)};")
    # bottom panel: size
    out.append("\\nextgroupplot[height=2.2cm, ymode=log, ymin=1.5, ymax=60, ytick={2,5,10,20,50},")
    out.append("  yticklabels={2,5,10,20,50}, ylabel={Size}, log basis y=10]")
    for label, _, _, _, style in SERIES:
        coords = " ".join(f"({g},{sz})" for g, _, sz in data[label])
        out.append(f"\\addplot[{style}] coordinates {{{coords}}};")
    out.append("\\end{groupplot}")
    out.append("\\end{tikzpicture}")
    with open(OUT, "w") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
