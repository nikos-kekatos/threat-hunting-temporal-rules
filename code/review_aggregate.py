#!/usr/bin/env python3
"""Aggregate the review 2026-10-21 experiments -> results_review_2026-10-21/SUMMARY.md.

Sources (written by code/review_2026-10-21.sh):
  results_xai_v2/gap1-G_s*/mine_b1/results/event_recall.json        (three episodes per host)
  results_review_1ep/gap1-G_s*/mine_b1/results/event_recall.json    (one episode per host)
  results_review_1ep/SUMMARY.md                                      (xai_aggregate over the 1-episode runs)
  results_xai_v2/gap1-G_s*/mine_b1/results/anchor_frozen_L{3,8}.json
  results_xai/noise*_s*/mine_b1/results/anchor_frozen_L3.json
  results_dc/mine_s*/results/anchor_frozen_L3.json                  (MAWI)
Means over seeds (or splits) with sample s.d.; event recall per delay pooled over seeds as k/n.
"""
import collections
import glob
import json
import os
import re
import statistics

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
OUT = os.path.join(ROOT, "results_review_2026-10-21")


def ms(xs):
    return "%.3f +- %.3f" % (statistics.mean(xs), statistics.stdev(xs)) if len(xs) > 1 else "%.3f" % xs[0]


def event_section(base, title):
    lines = ["## Event-level recall, %s" % title, "",
             "Host F1 and host recall: mean +- s.d. over seeds. Event recall: matched episodes / all episodes "
             "of anomalous held-out hosts, pooled over seeds. Benign B: benign B seconds matched / all.", "",
             "| G | method | L | host F1 | host R | event R | k/n | benign B | event recall by delay g (k/n, pooled) |",
             "|---|---|---|---|---|---|---|---|---|"]
    for g in (2, 4, 6, 8):
        acc = collections.OrderedDict()
        for p in sorted(glob.glob(os.path.join(base, "gap1-%d_s*" % g, "mine_b1", "results", "event_recall.json"))):
            for m in json.load(open(p))["methods"]:
                k = (m["method"], m["lags"])
                a = acc.setdefault(k, {"f1": [], "r": [], "k": 0, "n": 0, "bk": 0, "bn": 0,
                                       "by": collections.defaultdict(lambda: [0, 0])})
                a["f1"].append(m["host"]["f1"]); a["r"].append(m["host"]["recall"])
                a["k"] += m["matched"]; a["n"] += m["episodes"]
                a["bk"] += m["benign_b_matched"]; a["bn"] += m["benign_b_total"]
                for d, v in m["by_delay"].items():
                    a["by"][int(d)][0] += v["matched"]; a["by"][int(d)][1] += v["total"]
        for (meth, L), a in acc.items():
            by = " ".join("%d:%d/%d" % (d, v[0], v[1]) for d, v in sorted(a["by"].items()))
            lines.append("| %d | %s | %s | %s | %s | %.3f | %d/%d | %d/%d | %s |" % (
                g, meth, L if L else "-", ms(a["f1"]), ms(a["r"]), a["k"] / a["n"], a["k"], a["n"],
                a["bk"], a["bn"], by))
    return lines + [""]


def anchor_section(pattern, title, cfg_re):
    lines = ["## Anchors selected on training/validation hosts, frozen, scored on the test half: %s" % title, "",
             "| config | L | method | validation F1 | test P | test R | test F1 | planted | query (first run) |",
             "|---|---|---|---|---|---|---|---|---|"]
    acc = collections.OrderedDict()
    for p in sorted(glob.glob(pattern)):
        cfg = re.search(cfg_re, p).group(1)
        L = re.search(r"anchor_frozen_L(\d+)", p).group(1)
        d = json.load(open(p))
        for m in d["methods"]:
            a = acc.setdefault((cfg, L, m["method"]), {"v": [], "p": [], "r": [], "f": [], "pl": [], "q": m["query"],
                                                       "nt": []})
            if m.get("validation"):
                a["v"].append(m["validation"]["f1"])
            a["p"].append(m["test"]["precision"]); a["r"].append(m["test"]["recall"]); a["f"].append(m["test"]["f1"])
            a["pl"].append(m.get("planted_recovered")); a["nt"].append(d["n_test"])
    for (cfg, L, meth), a in acc.items():
        pl = "-" if a["pl"][0] is None or meth.startswith("gbm") else "%d/%d" % (sum(bool(x) for x in a["pl"]), len(a["pl"]))
        lines.append("| %s | L%s | %s | %s | %s | %s | %s | %s | %s |" % (
            cfg, L, meth, ms(a["v"]) if a["v"] else "-", ms(a["p"]), ms(a["r"]), ms(a["f"]), pl,
            a["q"][:80].replace("|", "/")))
    nts = sorted({n for a in acc.values() for n in a["nt"]})
    return lines + ["", "test-half sizes: %s" % nts, ""]


def main():
    os.makedirs(OUT, exist_ok=True)
    L = ["# Review 2026-10-21 experiments (generated by code/review_aggregate.py)", ""]
    L += event_section(os.path.join(ROOT, "results_xai_v2"), "three episodes per host (results_xai_v2)")
    L += event_section(os.path.join(ROOT, "results_review_1ep"), "one episode per host (results_review_1ep)")
    L += anchor_section(os.path.join(ROOT, "results_xai_v2", "gap1-*_s*", "mine_b1", "results", "anchor_frozen_L*.json"),
                        "delay sweep", r"(gap1-\d+)_s")
    L += anchor_section(os.path.join(ROOT, "results_xai", "noise*_s*", "mine_b1", "results", "anchor_frozen_L3.json"),
                        "stray events", r"(noise[\d.]+)_s")
    L += anchor_section(os.path.join(ROOT, "results_dc", "mine_s*", "results", "anchor_frozen_L3.json"),
                        "MAWI five splits", r"(results_dc)")
    open(os.path.join(OUT, "SUMMARY.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
