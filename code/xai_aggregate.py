#!/usr/bin/env python3
"""Aggregate results_xai/<config>_s<seed>/mine/results/xai_L*.json over seeds -> results_xai/SUMMARY.md.

mine/ is PSIMiner at bias 0, mine_b1/ at bias +1 (rows *_b1). For every config, lag budget and method: host F1 and F1 on permuted test traces (mean +- sd over
seeds), the number of seeds on which the planted order was recovered, and the explanation size.
usage: xai_aggregate.py [RESULTS_XAI_DIR]
"""
import collections
import glob
import json
import os
import re
import statistics
import sys

R = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "results_xai")


def ms(xs):
    return "%.3f +- %.3f" % (statistics.mean(xs), statistics.stdev(xs)) if len(xs) > 1 else "%.3f" % xs[0]


def main():
    acc = collections.defaultdict(lambda: {"f1": [], "f1p": [], "planted": [], "size": []})
    order = []
    for p in sorted(glob.glob(os.path.join(R, "*_s*", "mine*", "results", "xai_L*.json"))):
        cfg = re.sub(r"_s\d+$", "", p.split(os.sep)[-4])
        b1 = p.split(os.sep)[-3] == "mine_b1"
        b1_only = not os.path.exists(os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(p))), "mine"))
        lags = re.search(r"xai_(L\d+)", p).group(1)
        for m in json.load(open(p))["methods"]:
            if b1 and not b1_only and not m["method"].startswith("psiminer"):
                continue        # the other methods do not depend on the PSIMiner bias
            key = (cfg, lags, m["method"] + ("_b1" if b1 and m["method"].startswith("psiminer") else ""),
                   m.get("view", ""))
            if key not in acc:
                order.append(key)
            a = acc[key]
            if "skipped" in m:
                a["f1"].append(0.0)
                a["planted"].append(False)
                a["size"].append("none")
                continue
            a["f1"].append(m["host"]["f1"])
            if m.get("host_permuted"):
                a["f1p"].append(m["host_permuted"]["f1"])
            a["planted"].append(bool(m.get("planted_recovered")))
            a["size"].append(m["size"])
    lines = ["# Synthetic XAI comparison (generated by code/xai_aggregate.py)", "",
             "| config | lags | method | view | F1 | F1 permuted test | planted (seeds) | size (seed 1) |",
             "|---|---|---|---|---|---|---|---|"]
    for k in sorted(order, key=lambda k: (k[0], k[1], order.index(k))):
        a = acc[k]
        lines.append("| %s | %s | %s | %s | %s | %s | %d/%d | %s |" % (
            k[0], k[1], k[2], k[3], ms(a["f1"]), ms(a["f1p"]) if a["f1p"] else "-",
            sum(a["planted"]), len(a["planted"]), a["size"][0]))
    open(os.path.join(R, "SUMMARY.md"), "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
